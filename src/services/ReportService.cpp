QString ReportTable::cell(int r, int c) const
{
    const QVariant v = rows[r].value(c);
    if (moneyColumns.contains(c)) return Money::format(v.toLongLong(), false);
    return v.toString();
}

QVariantList ReportTable::totals() const
{
    if (totalColumns.isEmpty()) return {};
    QVariantList t;
    for (int c = 0; c < headers.size(); ++c) {
        if (!totalColumns.contains(c)) { t << (c == 0 ? QVariant(QObject::tr("Total")) : QVariant()); continue; }
        qint64 sum = 0;
        for (const auto &r : rows) sum += r.value(c).toLongLong();
        t << sum;
    }
    return t;
}

static QString csvCell(QString s)
{
    // Guards against spreadsheet formula injection and quotes every cell.
    if (!s.isEmpty() && QString("=+-@").contains(s.at(0)) && !(s.at(0) == '-' && s.size() > 1 && s.at(1).isDigit())) s.prepend('\'');
    return '"' + s.replace('"', "\"\"") + '"';
}

QString ReportTable::toCsv() const
{
    QStringList out;
    QStringList h;
    for (const auto &x : headers) h << csvCell(x);
    out << h.join(',');
    for (int r = 0; r < rows.size(); ++r) {
        QStringList line;
        for (int c = 0; c < headers.size(); ++c)
            line << csvCell(moneyColumns.contains(c) ? QString::number(rows[r].value(c).toLongLong() / 100.0, 'f', 2) : rows[r].value(c).toString());
        out << line.join(',');
    }
    const QVariantList t = totals();
    if (!t.isEmpty()) {
        QStringList line;
        for (int c = 0; c < t.size(); ++c)
            line << csvCell(totalColumns.contains(c) && moneyColumns.contains(c) ? QString::number(t[c].toLongLong() / 100.0, 'f', 2) : t[c].toString());
        out << line.join(',');
    }
    return out.join("\r\n") + "\r\n";
}

QString ReportTable::toHtml(const QString &pharmacyName, const QString &period) const
{
    QString h = "<html><body style='font-family:\"Segoe UI\",Arial; font-size:9pt;'>";
    h += "<h2 style='margin:0;'>" + pharmacyName.toHtmlEscaped() + "</h2>";
    h += "<h3 style='margin:2px 0;'>" + title.toHtmlEscaped() + "</h3>";
    if (!period.isEmpty()) h += "<div>" + period.toHtmlEscaped() + "</div>";
    for (const QString &s : summary) h += "<div>" + s.toHtmlEscaped() + "</div>";
    h += "<br/><table width='100%' border='1' cellspacing='0' cellpadding='3' style='border-collapse:collapse;'><tr style='background:#ece8f8;'>";
    for (const auto &x : headers) h += "<th>" + x.toHtmlEscaped() + "</th>";
    h += "</tr>";
    for (int r = 0; r < rows.size(); ++r) {
        h += "<tr>";
        for (int c = 0; c < headers.size(); ++c)
            h += QString("<td%1>").arg(moneyColumns.contains(c) ? " align='right'" : "") + cell(r, c).toHtmlEscaped() + "</td>";
        h += "</tr>";
    }
    const QVariantList t = totals();
    if (!t.isEmpty()) {
        h += "<tr style='font-weight:bold;'>";
        for (int c = 0; c < t.size(); ++c)
            h += QString("<td%1>").arg(moneyColumns.contains(c) ? " align='right'" : "")
                 + (totalColumns.contains(c) && moneyColumns.contains(c) ? Money::format(t[c].toLongLong(), false) : t[c].toString()).toHtmlEscaped()
                 + "</td>";
        h += "</tr>";
    }
    h += "</table><br/><div style='font-size:8pt;'>" + QObject::tr("Generated by MediCare Pro on %1")
         .arg(QDateTime::currentDateTime().toString("dd-MM-yyyy hh:mm")).toHtmlEscaped() + "</div></body></html>";
    return h;
}


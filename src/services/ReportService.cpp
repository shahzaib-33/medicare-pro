static void fill(ReportTable &t, const QString &sql, std::initializer_list<QVariant> binds)
{
    QSqlQuery q = exec(sql, binds);
    while (q.next()) {
        QVariantList r;
        for (int c = 0; c < t.headers.size(); ++c) r << q.value(c);
        t.rows << r;
    }
}

static Paisa sum(const QString &sql, std::initializer_list<QVariant> binds) { return scalar(sql, binds, 0).toLongLong(); }

ReportTable run(const QString &code, const QString &from, const QString &to)
{
    ReportTable t;
    t.code = code;
    for (const auto &d : available()) if (d.code == code) t.title = d.title;
    if (t.title.isEmpty()) return t;   // not allowed or unknown
    const QString today = todayIso();
    const QString D = "date(%1,'localtime') BETWEEN ? AND ?";
    try {
        if (code == "profit_loss") {
            const Paisa sales = sum("SELECT COALESCE(SUM(total-tax),0) FROM sales WHERE status='completed' AND " + D.arg("ts"), {from, to});
            const Paisa ret = sum("SELECT COALESCE(SUM(total),0) FROM sales_returns WHERE " + D.arg("ts"), {from, to});
            const Paisa cogs = sum("SELECT COALESCE(SUM(cost_total),0) FROM sales WHERE status='completed' AND " + D.arg("ts"), {from, to});
            const Paisa retCost = sum("SELECT COALESCE(SUM(cost_total),0) FROM sales_returns WHERE " + D.arg("ts"), {from, to});
            const Paisa exp = sum("SELECT COALESCE(SUM(CASE WHEN status='reversal' THEN -amount ELSE amount END),0) FROM expenses "
                                  "WHERE expense_date BETWEEN ? AND ?", {from, to});
            const Paisa damaged = sum("SELECT COALESCE(SUM(-m.qty * m.unit_cost),0) FROM stock_movements m WHERE m.reason IN "
                                      "('expired_disposal','disposal') AND " + D.arg("m.ts"), {from, to});
            t.headers = {QObject::tr("Line"), QObject::tr("Amount")};
            t.moneyColumns = {1};
            const Paisa net = sales - ret;
            const Paisa gross = net - (cogs - retCost);
            t.rows = {{QObject::tr("Sales (without tax)"), sales},
                      {QObject::tr("Less sales returns"), -ret},
                      {QObject::tr("Net sales"), net},
                      {QObject::tr("Cost of medicines sold"), -(cogs - retCost)},
                      {QObject::tr("Gross profit"), gross},
                      {QObject::tr("Expenses"), -exp},
                      {QObject::tr("Expired and damaged stock written off"), -damaged},
                      {QObject::tr("Net profit"), gross - exp - damaged}};
        } else if (code == "sales_daily") {
            t.headers = {QObject::tr("Date"), QObject::tr("Invoices"), QObject::tr("Gross"), QObject::tr("Discount"), QObject::tr("Tax"),
                         QObject::tr("Net total"), QObject::tr("Cost"), QObject::tr("Profit")};
            t.moneyColumns = {2, 3, 4, 5, 6, 7};
            t.totalColumns = {1, 2, 3, 4, 5, 6, 7};
            fill(t, "SELECT date(ts,'localtime') d, COUNT(*), SUM(subtotal), SUM(discount), SUM(tax), SUM(total), SUM(cost_total), "
                    "SUM(total - tax - cost_total) FROM sales WHERE status='completed' AND " + D.arg("ts") + " GROUP BY d ORDER BY d", {from, to});
        } else if (code == "sales_invoices") {
            t.headers = {QObject::tr("Invoice"), QObject::tr("Date and time"), QObject::tr("Customer"), QObject::tr("Cashier"),
                         QObject::tr("Total"), QObject::tr("Paid"), QObject::tr("Offline")};
            t.moneyColumns = {4, 5};
            t.totalColumns = {4, 5};
            fill(t, "SELECT s.invoice_no, datetime(s.ts,'localtime'), COALESCE(c.name,''), COALESCE(u.full_name,''), s.total, s.paid, "
                    "CASE s.offline WHEN 1 THEN 'yes' ELSE '' END FROM sales s LEFT JOIN customers c ON c.id=s.customer_id "
                    "LEFT JOIN users u ON u.id=s.user_id WHERE " + D.arg("s.ts") + " ORDER BY s.id", {from, to});
        } else if (code == "sales_by_medicine") {
            t.headers = {QObject::tr("Medicine"), QObject::tr("Units sold"), QObject::tr("Sales"), QObject::tr("Cost"), QObject::tr("Profit")};
            t.moneyColumns = {2, 3, 4};
            t.totalColumns = {1, 2, 3, 4};
            fill(t, "SELECT m.brand_name || ' ' || COALESCE(m.strength,''), SUM(i.qty), SUM(i.line_total - i.tax), SUM(i.cost_total), "
                    "SUM(i.line_total - i.tax - i.cost_total) FROM sale_items i JOIN sales s ON s.id=i.sale_id "
                    "JOIN medicines m ON m.id=i.medicine_id WHERE s.status='completed' AND " + D.arg("s.ts") +
                    " GROUP BY m.id ORDER BY 3 DESC", {from, to});
        } else if (code == "payments") {
            t.headers = {QObject::tr("Method"), QObject::tr("Payments"), QObject::tr("Amount")};
            t.moneyColumns = {2};
            t.totalColumns = {1, 2};
            fill(t, "SELECT p.method, COUNT(*), SUM(p.amount) FROM sale_payments p JOIN sales s ON s.id=p.sale_id WHERE " + D.arg("s.ts") +
                    " GROUP BY p.method ORDER BY 3 DESC", {from, to});
            for (auto &r : t.rows) r[0] = PaymentMethods::label(r[0].toString());
        } else if (code == "sales_by_user") {
            t.headers = {QObject::tr("Cashier"), QObject::tr("Invoices"), QObject::tr("Total")};
            t.moneyColumns = {2};
            t.totalColumns = {1, 2};
            fill(t, "SELECT COALESCE(u.full_name,'-'), COUNT(*), SUM(s.total) FROM sales s LEFT JOIN users u ON u.id=s.user_id WHERE "
                    + D.arg("s.ts") + " GROUP BY s.user_id ORDER BY 3 DESC", {from, to});
        } else if (code == "returns") {
            t.headers = {QObject::tr("Return"), QObject::tr("Date"), QObject::tr("Invoice"), QObject::tr("Refund method"), QObject::tr("Reason"),
                         QObject::tr("Refund")};
            t.moneyColumns = {5};
            t.totalColumns = {5};
            fill(t, "SELECT 'R' || r.id, datetime(r.ts,'localtime'), s.invoice_no, r.refund_method, r.reason, r.total FROM sales_returns r "
                    "JOIN sales s ON s.id=r.sale_id WHERE " + D.arg("r.ts") + " ORDER BY r.id", {from, to});
            for (auto &r : t.rows) r[3] = PaymentMethods::label(r[3].toString());
        } else if (code == "tax") {
            t.headers = {QObject::tr("Line"), QObject::tr("Amount")};
            t.moneyColumns = {1};
            const Paisa out = sum("SELECT COALESCE(SUM(tax),0) FROM sales WHERE status='completed' AND " + D.arg("ts"), {from, to});
            const Paisa in = sum("SELECT COALESCE(SUM(tax),0) FROM purchase_invoices WHERE status='posted' AND invoice_date BETWEEN ? AND ?", {from, to});
            const Paisa taxable = sum("SELECT COALESCE(SUM(line_total - tax),0) FROM sale_items i JOIN sales s ON s.id=i.sale_id "
                                      "WHERE i.tax>0 AND s.status='completed' AND " + D.arg("s.ts"), {from, to});
            t.rows = {{QObject::tr("Taxable sales"), taxable}, {QObject::tr("Sales tax collected"), out},
                      {QObject::tr("Sales tax paid on purchases"), in}, {QObject::tr("Difference"), out - in}};
        } else if (code == "purchases") {
            t.headers = {QObject::tr("Supplier"), QObject::tr("Invoice"), QObject::tr("Date"), QObject::tr("Status"), QObject::tr("Total"),
                         QObject::tr("Paid"), QObject::tr("Due")};
            t.moneyColumns = {4, 5, 6};
            t.totalColumns = {4, 5, 6};
            fill(t, "SELECT sp.name, p.invoice_no, p.invoice_date, p.status, p.total, p.paid, CASE WHEN p.status='posted' THEN p.total-p.paid ELSE 0 END "
                    "FROM purchase_invoices p JOIN suppliers sp ON sp.id=p.supplier_id WHERE p.invoice_date BETWEEN ? AND ? ORDER BY p.invoice_date, p.id",
                 {from, to});
        } else if (code == "expenses") {
            t.headers = {QObject::tr("Date"), QObject::tr("Category"), QObject::tr("Description"), QObject::tr("Method"), QObject::tr("Status"),
                         QObject::tr("Amount")};
            t.moneyColumns = {5};
            t.totalColumns = {5};
            fill(t, "SELECT e.expense_date, c.name, e.description, e.method, e.status, CASE WHEN e.status='reversal' THEN -e.amount ELSE e.amount END "
                    "FROM expenses e JOIN expense_categories c ON c.id=e.category_id WHERE e.expense_date BETWEEN ? AND ? ORDER BY e.expense_date, e.id",
                 {from, to});
        } else if (code == "supplier_balances") {
            t.headers = {QObject::tr("Supplier"), QObject::tr("Phone"), QObject::tr("Balance owed")};
            t.moneyColumns = {2};
            t.totalColumns = {2};
            fill(t, "SELECT s.name, COALESCE(s.phone,''), COALESCE(SUM(l.credit - l.debit),0) b FROM suppliers s "
                    "LEFT JOIN supplier_ledger l ON l.supplier_id=s.id GROUP BY s.id HAVING b<>0 ORDER BY b DESC", {});
        } else if (code == "customer_balances") {
            t.headers = {QObject::tr("Customer"), QObject::tr("Phone"), QObject::tr("Credit limit"), QObject::tr("Balance due")};
            t.moneyColumns = {2, 3};
            t.totalColumns = {3};
            fill(t, "SELECT c.name, COALESCE(c.phone,''), c.credit_limit, COALESCE(SUM(l.debit - l.credit),0) b FROM customers c "
                    "LEFT JOIN customer_ledger l ON l.customer_id=c.id GROUP BY c.id HAVING b<>0 ORDER BY b DESC", {});
        } else if (code == "stock_valuation") {
            t.headers = {QObject::tr("Medicine"), QObject::tr("Available"), QObject::tr("Quarantine"), QObject::tr("Damaged"),
                         QObject::tr("Cost value"), QObject::tr("Sale value")};
            t.moneyColumns = {4, 5};
            t.totalColumns = {1, 2, 3, 4, 5};
            fill(t, "SELECT m.brand_name || ' ' || COALESCE(m.strength,''), SUM(b.qty_available), SUM(b.qty_quarantine), SUM(b.qty_damaged), "
                    "SUM(b.qty_available * b.unit_cost), SUM(b.qty_available * COALESCE(b.sale_price, m.sale_price, 0)) "
                    "FROM medicine_batches b JOIN medicines m ON m.id=b.medicine_id WHERE b.expiry_date > ? "
                    "GROUP BY m.id HAVING SUM(b.qty_available + b.qty_quarantine + b.qty_damaged) > 0 ORDER BY 5 DESC", {today});
            t.summary << QObject::tr("Expired batches are not included in the value.");
        } else if (code == "low_stock") {
            t.headers = {QObject::tr("Medicine"), QObject::tr("Saleable stock"), QObject::tr("Minimum stock"), QObject::tr("Supplier")};
            fill(t, "SELECT m.brand_name || ' ' || COALESCE(m.strength,''), COALESCE((SELECT SUM(qty_available) FROM medicine_batches b "
                    "WHERE b.medicine_id=m.id AND b.status='active' AND b.expiry_date > ?),0) q, m.min_stock, COALESCE(s.name,'') "
                    "FROM medicines m LEFT JOIN suppliers s ON s.id=m.supplier_id WHERE m.archived=0 AND m.min_stock > 0 AND q <= m.min_stock "
                    "ORDER BY q", {today});
        } else if (code == "expiry") {
            t.headers = {QObject::tr("Medicine"), QObject::tr("Batch"), QObject::tr("Expiry"), QObject::tr("Days left"), QObject::tr("Quantity"),
                         QObject::tr("Cost value")};
            t.moneyColumns = {5};
            t.totalColumns = {4, 5};
            fill(t, "SELECT m.brand_name || ' ' || COALESCE(m.strength,''), b.batch_no, b.expiry_date, "
                    "CAST(julianday(b.expiry_date) - julianday(?) AS INTEGER), b.qty_available + b.qty_quarantine, "
                    "(b.qty_available + b.qty_quarantine) * b.unit_cost FROM medicine_batches b JOIN medicines m ON m.id=b.medicine_id "
                    "WHERE b.qty_available + b.qty_quarantine > 0 AND b.expiry_date <= date(?, '+90 day') ORDER BY b.expiry_date", {today, today});
        } else if (code == "movements") {
            t.headers = {QObject::tr("Date and time"), QObject::tr("Medicine"), QObject::tr("Batch"), QObject::tr("Stock type"), QObject::tr("Change"),
                         QObject::tr("Reason"), QObject::tr("User"), QObject::tr("Note")};
            fill(t, "SELECT datetime(mv.ts,'localtime'), m.brand_name, b.batch_no, mv.bucket, mv.qty, mv.reason, COALESCE(u.full_name,''), "
                    "COALESCE(mv.note,'') FROM stock_movements mv JOIN medicines m ON m.id=mv.medicine_id JOIN medicine_batches b ON b.id=mv.batch_id "
                    "LEFT JOIN users u ON u.id=mv.user_id WHERE " + D.arg("mv.ts") + " ORDER BY mv.id", {from, to});
        } else if (code == "shifts") {
            t.headers = {QObject::tr("User"), QObject::tr("Opened"), QObject::tr("Closed"), QObject::tr("Opening cash"), QObject::tr("Expected"),
                         QObject::tr("Counted"), QObject::tr("Difference")};
            t.moneyColumns = {3, 4, 5, 6};
            t.totalColumns = {6};
            fill(t, "SELECT u.full_name, datetime(s.opened_at,'localtime'), COALESCE(datetime(s.closed_at,'localtime'),''), s.opening_cash, "
                    "s.expected_cash, s.actual_cash, s.variance FROM cash_shifts s JOIN users u ON u.id=s.user_id WHERE " + D.arg("s.opened_at") +
                    " ORDER BY s.id", {from, to});
        } else if (code == "audit") {
            t.headers = {QObject::tr("Date and time"), QObject::tr("User"), QObject::tr("Action"), QObject::tr("Record"), QObject::tr("Details")};
            fill(t, "SELECT datetime(a.ts,'localtime'), COALESCE(u.full_name,''), a.action, COALESCE(a.entity,'') || ' ' || COALESCE(a.entity_id,''), "
                    "COALESCE(a.details,'') FROM audit_logs a LEFT JOIN users u ON u.id=a.user_id WHERE " + D.arg("a.ts") + " ORDER BY a.id DESC", {from, to});
        } else if (code == "logins") {
            t.headers = {QObject::tr("Date and time"), QObject::tr("Username"), QObject::tr("Event")};
            fill(t, "SELECT datetime(ts,'localtime'), username, event FROM login_history WHERE " + D.arg("ts") + " ORDER BY id DESC", {from, to});
        }
    } catch (const ServiceError &e) {
        t.summary << e.message;
    }
    return t;
}

Kpis kpis(const QString &from, const QString &to)
{
    Kpis k;
    const QString today = todayIso();
    const QString D = "date(%1,'localtime') BETWEEN ? AND ?";
    try {
        k.sales = sum("SELECT COALESCE(SUM(total),0) FROM sales WHERE status='completed' AND " + D.arg("ts"), {from, to});
        k.invoices = scalar("SELECT COUNT(*) FROM sales WHERE status='completed' AND " + D.arg("ts"), {from, to}).toInt();
        k.returns = sum("SELECT COALESCE(SUM(total),0) FROM sales_returns WHERE " + D.arg("ts"), {from, to});
        k.cost = sum("SELECT COALESCE(SUM(cost_total),0) FROM sales WHERE status='completed' AND " + D.arg("ts"), {from, to})
                 - sum("SELECT COALESCE(SUM(cost_total),0) FROM sales_returns WHERE " + D.arg("ts"), {from, to});
        const Paisa tax = sum("SELECT COALESCE(SUM(tax),0) FROM sales WHERE status='completed' AND " + D.arg("ts"), {from, to});
        k.expenses = sum("SELECT COALESCE(SUM(CASE WHEN status='reversal' THEN -amount ELSE amount END),0) FROM expenses "
                         "WHERE expense_date BETWEEN ? AND ?", {from, to});
        k.purchases = sum("SELECT COALESCE(SUM(total),0) FROM purchase_invoices WHERE status='posted' AND invoice_date BETWEEN ? AND ?", {from, to});
        k.profit = k.sales - tax - k.returns - k.cost - k.expenses;
        k.receivable = sum("SELECT COALESCE(SUM(debit - credit),0) FROM customer_ledger", {});
        k.payable = sum("SELECT COALESCE(SUM(credit - debit),0) FROM supplier_ledger", {});
        k.lowStock = scalar("SELECT COUNT(*) FROM medicines m WHERE m.archived=0 AND m.min_stock>0 AND COALESCE((SELECT SUM(qty_available) "
                            "FROM medicine_batches b WHERE b.medicine_id=m.id AND b.status='active' AND b.expiry_date>?),0) <= m.min_stock", {today}).toInt();
        k.expiring30 = scalar("SELECT COUNT(*) FROM medicine_batches WHERE qty_available>0 AND expiry_date>? AND expiry_date<=date(?,'+30 day')",
                              {today, today}).toInt();
        k.expired = scalar("SELECT COUNT(*) FROM medicine_batches WHERE qty_available+qty_quarantine>0 AND expiry_date<=?", {today}).toInt();
        k.pendingRx = scalar("SELECT COUNT(*) FROM prescriptions WHERE status='pending'").toInt();
        k.pendingInspections = scalar("SELECT COUNT(*) FROM sales_return_items WHERE disposition='pending'").toInt();
        k.reviewFlags = scalar("SELECT COUNT(*) FROM medicine_review_flags WHERE resolved_at IS NULL").toInt();
    } catch (const ServiceError &) {
    }
    return k;
}

QVector<QPair<QString, Paisa>> dailySales(const QString &from, const QString &to)
{
    QVector<QPair<QString, Paisa>> out;
    QHash<QString, Paisa> byDay;
    try {
        QSqlQuery q = exec("SELECT date(ts,'localtime') d, SUM(total) FROM sales WHERE status='completed' AND date(ts,'localtime') BETWEEN ? AND ? "
                           "GROUP BY d", {from, to});
        while (q.next()) byDay.insert(q.value(0).toString(), q.value(1).toLongLong());
    } catch (const ServiceError &) {
    }
    QDate d = QDate::fromString(from, Qt::ISODate);
    const QDate end = QDate::fromString(to, Qt::ISODate);
    for (int guard = 0; d.isValid() && d <= end && guard < 400; d = d.addDays(1), ++guard)
        out.append({d.toString(Qt::ISODate), byDay.value(d.toString(Qt::ISODate))});
    return out;
}

QVector<QPair<QString, Paisa>> paymentSplit(const QString &from, const QString &to)
{
    QVector<QPair<QString, Paisa>> out;
    try {
        QSqlQuery q = exec("SELECT p.method, SUM(p.amount) FROM sale_payments p JOIN sales s ON s.id=p.sale_id "
                           "WHERE date(s.ts,'localtime') BETWEEN ? AND ? GROUP BY p.method ORDER BY 2 DESC", {from, to});
        while (q.next()) out.append({PaymentMethods::label(q.value(0).toString()), q.value(1).toLongLong()});
    } catch (const ServiceError &) {
    }
    return out;
}

QVector<QPair<QString, int>> topMedicines(const QString &from, const QString &to, int limit)
{
    QVector<QPair<QString, int>> out;
    try {
        QSqlQuery q = exec("SELECT m.brand_name, SUM(i.qty) FROM sale_items i JOIN sales s ON s.id=i.sale_id JOIN medicines m ON m.id=i.medicine_id "
                           "WHERE date(s.ts,'localtime') BETWEEN ? AND ? GROUP BY m.id ORDER BY 2 DESC LIMIT ?", {from, to, limit});
        while (q.next()) out.append({q.value(0).toString(), q.value(1).toInt()});
    } catch (const ServiceError &) {
    }
    return out;
}
